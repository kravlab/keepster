/*
 * PROTOTYPE (ticket 09) — builds each engine alone and reports raw/gzip/brotli weight.
 *
 * "Eager" is the transitive *static* import closure of the entry plus the CSS it pulls: what a
 * browser must download before the editor can render anything. Everything else is reached only
 * through a dynamic import (a language grammar, a worker) and is therefore pay-per-use.
 */
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { gzipSync, brotliCompressSync, constants } from 'node:zlib'
import { join, relative } from 'node:path'

const TARGETS = ['cm6', 'monaco', 'monaco-core']
const LABELS = {
  cm6: 'CodeMirror 6 (MergeView, 13 lazy languages)',
  monaco: 'Monaco — package entry (all grammars + LSP client)',
  'monaco-core': 'Monaco — editor.api + the curated 13 languages only',
}

const walk = (dir) =>
  readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]))

const kib = (n) => (n / 1024).toFixed(1)
const sum = (list, key) => list.reduce((a, f) => a + f[key], 0)

const report = {}
for (const target of TARGETS) {
  execFileSync('pnpm', ['exec', 'vite', 'build', '--config', 'measure/vite.config.mjs'], {
    stdio: ['ignore', 'ignore', 'inherit'],
    env: { ...process.env, MEASURE_TARGET: target },
  })
  const dir = `measure/out/${target}`
  const meta = JSON.parse(readFileSync(join(dir, 'meta.json'), 'utf8'))
  const byFile = new Map(meta.map((c) => [c.file, c]))

  // Static closure from the entry chunk.
  const eagerFiles = new Set()
  const queue = meta.filter((c) => c.isEntry).map((c) => c.file)
  while (queue.length) {
    const f = queue.pop()
    if (eagerFiles.has(f)) continue
    eagerFiles.add(f)
    const c = byFile.get(f)
    if (!c) continue
    for (const css of c.css) eagerFiles.add(css)
    queue.push(...c.imports)
  }

  const files = walk(dir)
    .filter((f) => f.endsWith('.js') || f.endsWith('.css'))
    .map((f) => {
      const buf = readFileSync(f)
      const rel = relative(dir, f)
      return {
        file: rel,
        eager: eagerFiles.has(rel),
        raw: buf.length,
        gzip: gzipSync(buf, { level: 9 }).length,
        brotli: brotliCompressSync(buf, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).length,
      }
    })
    .sort((a, b) => b.raw - a.raw)

  const eager = files.filter((f) => f.eager)
  report[target] = { files, eager }
}

let md = `# Editor bake-off — bundle weight

_Generated by \`pnpm measure\` (throwaway prototype, wayfinder ticket 09). One Vite 8 build per engine,
oxc-minified, ES2022, no application code beyond the adapter itself._

**Eager** = the static import closure of the entry: what the browser must have before the editor paints.
**Total** = eager plus every lazily reachable chunk (language grammars, workers).

| build | eager raw | eager gzip | eager brotli | total raw | total gzip | total brotli |
| --- | --- | --- | --- | --- | --- | --- |
`
for (const t of TARGETS) {
  const { files, eager } = report[t]
  md += `| ${LABELS[t]} | ${kib(sum(eager, 'raw'))} KiB | ${kib(sum(eager, 'gzip'))} KiB | ${kib(sum(eager, 'brotli'))} KiB | ${kib(sum(files, 'raw'))} KiB | ${kib(sum(files, 'gzip'))} KiB | ${kib(sum(files, 'brotli'))} KiB |\n`
}
for (const t of TARGETS) {
  md += `\n## ${t} — chunks\n\n| file | eager | raw | gzip | brotli |\n| --- | --- | --- | --- | --- |\n`
  for (const f of report[t].files) {
    md += `| \`${f.file}\` | ${f.eager ? 'yes' : 'lazy'} | ${kib(f.raw)} KiB | ${kib(f.gzip)} KiB | ${kib(f.brotli)} KiB |\n`
  }
}

writeFileSync('measure/REPORT.md', md)
process.stdout.write(md.split('\n## ')[0])
